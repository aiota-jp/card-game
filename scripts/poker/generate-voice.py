"""Generate the 40 bundled lines. Requires VOICEVOX CORE 0.17 and model 2.vvm.
Run in a build-only environment. No synthesis engine is shipped with the game.
VOICEVOX:九州そら (normal style 16). See docs/VOICE-CREDITS.ja.md.
"""
import argparse, array, hashlib, io, json, math, wave
from pathlib import Path
from voicevox_core.blocking import Onnxruntime, OpenJtalk, Synthesizer, VoiceModelFile

p=argparse.ArgumentParser();p.add_argument('--runtime',type=Path,required=True);p.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);p.add_argument('--character',choices=['misaki','ayaka','rina'],default='misaki');p.add_argument('--rewards',action='store_true');args=p.parse_args()
runtime=args.runtime.resolve();root=args.root.resolve();folder='voice' if args.character=='misaki' else 'voice-'+args.character;style=15 if args.character=='ayaka' else 18 if args.character=='rina' else 16;out=root/'frontend/assets'/folder;out.mkdir(parents=True,exist_ok=True)
onnx=Onnxruntime.load_once(filename=str(runtime/'onnxruntime/lib/voicevox_onnxruntime.dll'))
synth=Synthesizer(onnx,OpenJtalk(str(runtime/'dict/open_jtalk_dic_utf_8-1.11')),acceleration_mode='CPU',cpu_num_threads=4)
with VoiceModelFile.open(str(runtime/'models/vvms/2.vvm')) as model:synth.load_voice_model(model)
lines=json.loads((root/('scripts/'+args.character+'-reward-lines.json' if args.rewards else 'scripts/voice-lines.json' if args.character=='misaki' else 'scripts/'+args.character+'-lines.json')).read_text(encoding='utf-8-sig'))
profiles={'reward':(1.02,0,1.08),'welcome':(1.02,.0,1.05),'deal':(1.06,.0,1.03),'win':(1.08,.015,1.16),'loss':(.99,-.005,.96),'tie':(1.04,.005,1.07),'draw':(1.01,.0,1.02),'reveal':(1.02,.005,1.10),'raise':(1.06,.01,1.14),'streakWin':(1.07,.012,1.16),'streakLoss':(.98,-.005,.96),'fold':(1.0,.0,1.0)}
manifest=[]
for n,line in enumerate(lines):
    entry=dict(line);entry['files']={}
    for mode in ['expressive','calm']:
        query_style=16 if args.character=='rina' else style
        query=synth.create_audio_query(line['text'],query_style)
        query.speed_scale,query.pitch_scale,query.intonation_scale=profiles[line['kind']] if mode=='expressive' else (1.03,0,.85)
        if args.character=='ayaka':
            query.pitch_scale+=.04;query.intonation_scale*=1.04
        elif args.character=='rina':
            query.pitch_scale+=.035;query.intonation_scale*=.98;query.speed_scale*=1.06
        pauses=[]
        for phrase in query.accent_phrases:
            if phrase.pause_mora is not None:
                original=phrase.pause_mora['vowel_length'];shortened=min(original,max(.10,min(.40,original*.45)));phrase.pause_mora['vowel_length']=shortened;pauses.append({'before':round(original,4),'after':round(shortened,4)})
        query.pre_phoneme_length=.02;query.post_phoneme_length=.06;query.output_sampling_rate=24000;query.output_stereo=False
        audio=synth.synthesis(query,style)
        with wave.open(io.BytesIO(audio),'rb') as f:
            params=f.getparams();data=array.array('h',f.readframes(f.getnframes()))
        peak=max(abs(x) for x in data)
        if peak==0:raise RuntimeError('Silent output')
        gain=min(.85*32767/peak,1.8)
        data=array.array('h',(max(-32767,min(32767,round(x*gain))) for x in data))
        path=out/f"{line['id']}-{mode}.wav"
        with wave.open(str(path),'wb') as f:f.setparams(params);f.writeframes(data.tobytes())
        entry['files'][mode]={'path':f'assets/{folder}/{path.name}','duration':round(len(data)/24000,3),'pauses':pauses,'voice':{'styleId':style,'queryStyleId':query_style,'pitchScale':query.pitch_scale,'speedScale':query.speed_scale,'intonationScale':query.intonation_scale},'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
    manifest.append(entry);print(f"{n+1}/{len(lines)} {line['id']}",flush=True)
(out/('reward-manifest.json' if args.rewards else 'manifest.json')).write_text(json.dumps({'credit':'VOICEVOX:九州そら','core':'0.17.0','styleId':style,'lines':manifest},ensure_ascii=False,indent=2),encoding='utf-8')
(root/('frontend/'+args.character+'-reward-lines.js' if args.rewards else 'frontend/voice-lines.js' if args.character=='misaki' else 'frontend/'+args.character+'-voice-lines.js')).write_text('// Generated by scripts/generate-voice.py. VOICEVOX:九州そら\nexport const voiceLines = '+json.dumps(manifest,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
